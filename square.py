def area(a):
    '''
    Возвращает площадь квадрата по заданной стороне.

        Параметры:
            a (int | float): длина стороны квадрата

        Возвращаемое значение:
            int | float: площадь квадрата

        Пример вызова:
            area(5) -> 25
    '''
    return a * a


